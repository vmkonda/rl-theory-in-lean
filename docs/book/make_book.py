#!/usr/bin/env python3
"""Generate the book's chapter files from the chapter sources in docs/.

Each docs/<name>.tex is a standalone article. For the book, its body becomes a chapter:
the title and contents are dropped, the abstract becomes the chapter's opening paragraph,
labels and references get a per-chapter prefix (so `thm:cov` in two chapters do not clash),
figure paths are made relative to the book, and the bibliographies are merged.

Usage: python3 make_book.py   (writes build/ch-*.tex and build/bibliography.tex)
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DOCS = os.path.dirname(HERE)
OUT = os.path.join(HERE, "build")

# (prefix, source, chapter title, short title for the running head)
CHAPTERS = [
    ("pg", "policy-gradient", "Policy Gradients for Discounted Finite MDPs",
     "Policy gradients"),
    ("td", "td-lambda-rates", r"Rates of Convergence of TD($\lambda$)",
     r"TD($\lambda$) rates"),
    ("cov", "markov-sa-covariance",
     "Asymptotic Covariance of Linear Stochastic Approximation with Markov Noise",
     "Markov-noise covariance"),
    ("tts", "two-time-scale-covariance",
     "Two-Time-Scale Stochastic Approximation with Markov Noise", "Two time scales"),
    ("ac", "actor-critic-rates", "Rates of Actor-Critic and Actor-Only Methods",
     "Actor-critic rates"),
]

REF_CMDS = ("label", "ref", "eqref", "pageref", "autoref", "cref", "Cref", "nameref")


def prefix_labels(text: str, pre: str) -> str:
    pat = re.compile(r"\\(" + "|".join(REF_CMDS) + r")\{([^}]*)\}")

    def rep(m):
        keys = ",".join(pre + ":" + k.strip() for k in m.group(2).split(","))
        return "\\" + m.group(1) + "{" + keys + "}"

    return pat.sub(rep, text)


def split_bib(body: str):
    m = re.search(r"\\begin\{thebibliography\}\{[^}]*\}(.*?)\\end\{thebibliography\}", body, re.S)
    if not m:
        return body, []
    items = []
    for chunk in re.split(r"(?=\\bibitem)", m.group(1)):
        chunk = chunk.strip()
        km = re.match(r"\\bibitem(\[[^\]]*\])?\{([^}]*)\}", chunk)
        if km:
            items.append((km.group(2), chunk))
    return body[:m.start()] + body[m.end():], items


def convert(pre: str, name: str, title: str, short: str):
    src = open(os.path.join(DOCS, name + ".tex")).read()
    body = src.split(r"\begin{document}", 1)[1].split(r"\end{document}", 1)[0]
    body, bib = split_bib(body)
    body = body.replace(r"\maketitle", "").replace(r"\tableofcontents", "")
    body = re.sub(r"\\begin\{abstract\}(.*?)\\end\{abstract\}",
                  lambda m: "\\begin{chapterabstract}" + m.group(1) + "\\end{chapterabstract}",
                  body, flags=re.S)
    body = prefix_labels(body, pre)
    body = body.replace("{figures/", "{../figures/")
    head = (f"% Generated from docs/{name}.tex by make_book.py; edit the source, not this file.\n"
            f"\\chapter{{{title}}}\\chaptermark{{{short}}}\\label{{ch:{pre}}}\n"
            f"\\chaptersource{{{name}}}\n")
    open(os.path.join(OUT, f"ch-{pre}.tex"), "w").write(head + body.strip() + "\n")
    return bib


def main():
    os.makedirs(OUT, exist_ok=True)
    merged, seen = [], set()
    for pre, name, title, short in CHAPTERS:
        for key, item in convert(pre, name, title, short):
            if key not in seen:
                seen.add(key)
                merged.append(item)
    with open(os.path.join(OUT, "bibliography.tex"), "w") as f:
        f.write("% Generated by make_book.py: the merged bibliographies of the chapters.\n")
        f.write("\\begin{thebibliography}{99}\n" + "\n".join(merged) + "\n\\end{thebibliography}\n")
    print(f"wrote {len(CHAPTERS)} chapters and {len(merged)} references to {OUT}", file=sys.stderr)


if __name__ == "__main__":
    main()
